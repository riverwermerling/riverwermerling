// Builds ONE self-contained file for pasting into the Supabase dashboard's function editor
// (the dashboard editor is easier than the CLI if you are not a developer).
// Run: node tools/bundle-function.mjs   -> supabase/paste-into-dashboard/send-reminders.ts
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join, dirname } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'supabase', 'functions', 'send-reminders');
export const outFile = join(root, 'supabase', 'paste-into-dashboard', 'send-reminders.ts');

export function build() {
  const schedule = readFileSync(join(dir, 'schedule.ts'), 'utf8').replace(/^export /gm, '');
  const index = readFileSync(join(dir, 'index.ts'), 'utf8');
  const imports = index.match(/^import .*from 'npm:.*';$/gm).join('\n');
  const body = index.replace(/^import .*;$/gm, '').trim();
  return `// GENERATED by tools/bundle-function.mjs. Do not edit; edit supabase/functions/send-reminders/ instead.\n${imports}\n\n${schedule.trim()}\n\n${body}\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, build());
  console.log(`wrote ${outFile}`);
}
